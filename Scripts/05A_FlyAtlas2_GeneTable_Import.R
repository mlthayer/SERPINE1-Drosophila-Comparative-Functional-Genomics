# ==============================================================================
# 9. CANONICALIZE TISSUE NAMES
# ==============================================================================

# FlyAtlas2 gene tables use "Brain / CNS".
#
# For the long-format dataset:
# Adult Brain / CNS -> Brain
# Larval Brain / CNS -> CNS
#
# Tissue_Raw is retained so the original FlyAtlas2 terminology is never lost.

flyatlas_gene_wide <- flyatlas_gene_wide %>%
    mutate(
        Adult_Tissue = case_when(
            Tissue_Raw == "Brain / CNS" ~ "Brain",
            TRUE ~ Tissue_Raw
        ),

        Larval_Tissue = case_when(
            Tissue_Raw == "Brain / CNS" ~ "CNS",
            TRUE ~ Tissue_Raw
        )
    )


