# ==============================================================================
# 2. HELPER FUNCTION FOR FLYATLAS2 NUMERIC VALUES
# ==============================================================================

# FlyAtlas2 uses "-" where a measurement is unavailable.
# IMPORTANT:
# "-" is converted to NA, NOT zero.
#
# Actual numeric zeros remain zero.

parse_flyatlas_number <- function(x) {

    x <- trimws(as.character(x))

    x[x %in% c(
        "",
        "-",
        "NA",
        "N/A"
    )] <- NA_character_

    suppressWarnings(
        as.numeric(x)
    )
}


# ==============================================================================
# 3. PARSER FOR ONE GENE-LEVEL FILE
# ==============================================================================

parse_flyatlas_gene_file <- function(file) {

    raw_lines <- readLines(
        file,
        warn = FALSE
    )

    # --------------------------------------------------------------------------
    # Basic file structure QC
    # --------------------------------------------------------------------------

    if (length(raw_lines) < 8) {
        stop(
            "File has fewer than 8 lines: ",
            basename(file)
        )
    }


    # --------------------------------------------------------------------------
    # Extract metadata
    # --------------------------------------------------------------------------

    get_metadata_value <- function(line) {

        parts <- strsplit(
            line,
            "\t",
            fixed = FALSE
        )[[1]]

        if (length(parts) < 2) {
            return(NA_character_)
        }

        trimws(parts[2])
    }


    flybase_id <- get_metadata_value(raw_lines[1])
    annotation_symbol <- get_metadata_value(raw_lines[2])
    gene <- get_metadata_value(raw_lines[3])
    gene_name <- get_metadata_value(raw_lines[4])


    # --------------------------------------------------------------------------
    # Read expression table
    #
    # Line 7 contains the actual column labels.
    # Expression data begin on line 8.
    # --------------------------------------------------------------------------

    expression_raw <- read.delim(
        file,
        skip = 6,
        header = TRUE,
        sep = "\t",
        check.names = FALSE,
        stringsAsFactors = FALSE,
        na.strings = character()
    )


    # --------------------------------------------------------------------------
    # Confirm expected number of columns
    # --------------------------------------------------------------------------

    if (ncol(expression_raw) != 12) {

        stop(
            "\nUnexpected number of columns in ",
            basename(file),
            ".\nExpected: 12\nObserved: ",
            ncol(expression_raw)
        )
    }


    # --------------------------------------------------------------------------
    # Assign explicit column names
    #
    # Do NOT depend on duplicated FPKM/SD/Enrichment names generated by R.
    # --------------------------------------------------------------------------

    names(expression_raw) <- c(
        "Tissue_Raw",

        "Male_FPKM",
        "Male_SD",
        "Male_Enrichment",

        "Female_FPKM",
        "Female_SD",
        "Female_Enrichment",

        "Male_Female_Ratio",
        "Male_Female_p",

        "Larval_FPKM",
        "Larval_SD",
        "Larval_Enrichment"
    )


    # --------------------------------------------------------------------------
    # Convert numeric columns
    # --------------------------------------------------------------------------

    numeric_columns <- c(
        "Male_FPKM",
        "Male_SD",
        "Male_Enrichment",
        "Female_FPKM",
        "Female_SD",
        "Female_Enrichment",
        "Male_Female_Ratio",
        "Larval_FPKM",
        "Larval_SD",
        "Larval_Enrichment"
    )


    expression_raw <- expression_raw %>%
        mutate(
            across(
                all_of(numeric_columns),
                parse_flyatlas_number
            )
        )


    # --------------------------------------------------------------------------
    # Add metadata
    # --------------------------------------------------------------------------

    expression_raw <- expression_raw %>%
        mutate(
            Gene = gene,
            FlyBase_ID = flybase_id,
            Annotation_Symbol = annotation_symbol,
            Gene_Name = gene_name,
            Source_File = basename(file),
            .before = 1
        )


    return(expression_raw)
}


