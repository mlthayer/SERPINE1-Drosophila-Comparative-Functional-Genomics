if (nzchar(Sys.getenv("SERPINE1_FLYATLAS_GENE_WIDE_INPUT")) ||
    (length(gene_table_files) == 0L && file.exists(gene_wide_input))) {
    # Preserve the supplied prepared input separately from generated outputs.
    flyatlas_gene_wide <- readr::read_csv(gene_wide_input, show_col_types = FALSE)
    required_wide_columns <- c(
        "Gene", "FlyBase_ID", "Annotation_Symbol", "Gene_Name", "Source_File",
        "Tissue_Raw", "Male_FPKM", "Male_SD", "Male_Enrichment",
        "Female_FPKM", "Female_SD", "Female_Enrichment", "Male_Female_Ratio",
        "Male_Female_p", "Larval_FPKM", "Larval_SD", "Larval_Enrichment")
    missing_wide_columns <- setdiff(required_wide_columns, names(flyatlas_gene_wide))
    if (length(missing_wide_columns)) {
        stop("Gene-level CSV is missing columns: ",
             paste(missing_wide_columns, collapse = ", "), call. = FALSE)
    }
    numeric_wide_columns <- setdiff(required_wide_columns, c(
        "Gene", "FlyBase_ID", "Annotation_Symbol", "Gene_Name", "Source_File",
        "Tissue_Raw", "Male_Female_p"))
    if (!all(vapply(flyatlas_gene_wide[numeric_wide_columns], is.numeric, logical(1)))) {
        stop("Gene-level expression columns must be numeric, with NA for missing values.",
             call. = FALSE)
    }
    message("Using prepared gene-level CSV; raw text parsing is not validated: ",
            gene_wide_input)
} else {
    if (length(gene_table_files) != 6L) {
        stop("Provide six original gene-level text exports in ", gene_input_dir,
             " or set SERPINE1_FLYATLAS_GENE_WIDE_INPUT to the prepared wide CSV.",
             call. = FALSE)
    }
    flyatlas_gene_wide <- map_dfr(gene_table_files, parse_flyatlas_gene_file)
}


